document.addEventListener('DOMContentLoaded', function () {

  // ---- Language (EN / DA / ES / FR) ----
  // English lives in the HTML. Other languages live in lang/<code>.json, keyed by
  // each element's data-i18n attribute (data-i18n-ph for input placeholders).
  // A saved choice wins; otherwise the browser's preferred language is used.
  var LANGS = ['en', 'da', 'es', 'fr'];
  var currentLang = 'en';
  var dict = {};
  var dictCache = {};
  var requestedLang = null;

  try {
    var saved = localStorage.getItem('lang');
    if (LANGS.indexOf(saved) !== -1) {
      currentLang = saved;
    } else {
      var prefs = navigator.languages || [navigator.language || ''];
      for (var i = 0; i < prefs.length; i++) {
        var code = String(prefs[i]).slice(0, 2).toLowerCase();
        if (LANGS.indexOf(code) !== -1) { currentLang = code; break; }
      }
    }
  } catch (e) {}

  // English fallbacks for text generated by this script (translated under "js.*").
  var EN = {
    projectsError: 'Could not load projects.',
    noDesc: 'No description available.',
    viewGithub: 'View on GitHub',
    loadMore: 'Load More Projects',
    loading: 'Loading…',
    sending: 'Sending…',
    sent: 'Sent!',
    formError: 'Error. Try again.'
  };
  function t(key) { return dict['js.' + key] || EN[key] || ''; }

  function loadDict(lang) {
    if (lang === 'en') return Promise.resolve({});
    if (dictCache[lang]) return Promise.resolve(dictCache[lang]);
    return fetch('lang/' + lang + '.json')
      .then(function (res) {
        if (!res.ok) throw new Error('HTTP ' + res.status);
        return res.json();
      })
      .then(function (data) { dictCache[lang] = data; return data; });
  }

  // Apply the loaded dictionary to the page; missing keys fall back to English.
  function renderLang() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var hasKids = el.children.length > 0;
      if (el.dataset.en === undefined) el.dataset.en = hasKids ? el.innerHTML : el.textContent;
      var val = dict[el.getAttribute('data-i18n')] || el.dataset.en;
      if (hasKids) { el.innerHTML = val; } else { el.textContent = val; }
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      if (el.dataset.enPh === undefined) el.dataset.enPh = el.getAttribute('placeholder') || '';
      el.setAttribute('placeholder', dict[el.getAttribute('data-i18n-ph')] || el.dataset.enPh);
    });
    document.querySelectorAll('[data-lang-btn]').forEach(function (b) {
      var active = b.getAttribute('data-lang-btn') === currentLang;
      b.classList.toggle('lang-active', active);
      b.setAttribute('aria-pressed', active ? 'true' : 'false');
    });
  }

  function applyLang(lang) {
    var next = LANGS.indexOf(lang) !== -1 ? lang : 'en';
    requestedLang = next;
    return loadDict(next)
      .then(function (data) {
        if (requestedLang !== next) return; // a newer choice was made meanwhile
        currentLang = next;
        dict = data;
        renderLang();
      })
      .catch(function (err) {
        console.error('Could not load language "' + next + '":', err);
        renderLang();
      });
  }

  document.querySelectorAll('[data-lang-btn]').forEach(function (b) {
    b.addEventListener('click', function () {
      var lang = b.getAttribute('data-lang-btn');
      try { localStorage.setItem('lang', lang); } catch (e) {}
      applyLang(lang);
    });
  });

  applyLang(currentLang);

  // ---- Copyright Year ----
  var yearEls = document.querySelectorAll('#copyright-year');
  yearEls.forEach(function (el) {
    el.textContent = new Date().getFullYear();
  });

  // ---- Mobile Menu Toggle ----
  var menuBtn = document.getElementById('mobile-menu-btn');
  var mobileMenu = document.getElementById('mobile-menu');
  var iconOpen = document.getElementById('menu-icon-open');
  var iconClose = document.getElementById('menu-icon-close');

  if (menuBtn && mobileMenu) {
    menuBtn.addEventListener('click', function () {
      var isHidden = mobileMenu.classList.toggle('hidden');
      if (iconOpen) iconOpen.classList.toggle('hidden', !isHidden);
      if (iconClose) iconClose.classList.toggle('hidden', isHidden);
    });
  }

  // ---- Header Shadow on Scroll ----
  var header = document.getElementById('header');
  if (header) {
    window.addEventListener('scroll', function () {
      header.classList.toggle('scrolled', window.scrollY > 10);
    }, { passive: true });
  }

  // ---- Fade-In on Scroll (IntersectionObserver) ----
  var fadeEls = document.querySelectorAll('.fade-in');
  if (fadeEls.length > 0 && 'IntersectionObserver' in window) {
    var obs = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
        }
      });
    }, { threshold: 0.1 });
    fadeEls.forEach(function (el) { obs.observe(el); });
  } else {
    // Fallback: show everything
    fadeEls.forEach(function (el) { el.classList.add('visible'); });
  }

  // ---- Quote Carousel ----
  var carousel = document.getElementById('quote-carousel');
  var quotePrev = document.getElementById('quote-prev');
  var quoteNext = document.getElementById('quote-next');
  var quoteCurrent = document.getElementById('quote-current');
  var quoteTotal = document.getElementById('quote-total');

  if (carousel) {
    var slides = carousel.querySelectorAll('.quote-slide');
    var currentIndex = 0;
    var autoplayTimer = null;

    if (quoteTotal) quoteTotal.textContent = String(slides.length).padStart(2, '0');

    function showSlide(index) {
      slides.forEach(function (slide, i) {
        slide.style.opacity = i === index ? '1' : '0';
        slide.classList.toggle('active', i === index);
      });
      if (quoteCurrent) quoteCurrent.textContent = String(index + 1).padStart(2, '0');
    }

    function nextSlide() {
      currentIndex = (currentIndex + 1) % slides.length;
      showSlide(currentIndex);
    }

    function prevSlide() {
      currentIndex = (currentIndex - 1 + slides.length) % slides.length;
      showSlide(currentIndex);
    }

    function resetAutoplay() {
      clearInterval(autoplayTimer);
      autoplayTimer = setInterval(nextSlide, 5000);
    }

    if (quoteNext) {
      quoteNext.addEventListener('click', function () {
        nextSlide();
        resetAutoplay();
      });
    }

    if (quotePrev) {
      quotePrev.addEventListener('click', function () {
        prevSlide();
        resetAutoplay();
      });
    }

    // Auto-rotate every 5 seconds
    autoplayTimer = setInterval(nextSlide, 5000);
  }

  // ---- GitHub Projects ----
  var projectsGrid = document.getElementById('projects-grid');
  var loadingProjects = document.getElementById('loading-projects');
  var loadMoreWrap = document.getElementById('load-more-wrap');
  var GITHUB_USERNAME = 'brayanvillatoro';
  var projectsPage = 1;
  var PER_PAGE = 9;

  function loadProjects(append) {
    if (!projectsGrid) return;

    var url = 'https://api.github.com/users/' + GITHUB_USERNAME +
      '/repos?sort=pushed&direction=desc&per_page=' + PER_PAGE + '&page=' + projectsPage;

    fetch(url)
      .then(function (res) {
        if (!res.ok) throw new Error('GitHub API error');
        return res.json();
      })
      .then(function (repos) {
        if (loadingProjects) loadingProjects.style.display = 'none';

        if (!append) projectsGrid.innerHTML = '';

        var visible = repos.filter(function (repo) { return !repo.fork && !repo.archived; });
        visible.forEach(function (repo) {
          var card = document.createElement('div');
          card.className = 'project-card fade-in visible';

          var title = document.createElement('h3');
          title.className = 'text-lg font-semibold text-[#1d1d1f] mt-4 mb-2';
          title.textContent = repo.name;

          var desc = document.createElement('p');
          desc.className = 'text-sm text-[#86868b] leading-relaxed mb-4';
          if (repo.description) {
            desc.textContent = repo.description;
          } else {
            desc.textContent = EN.noDesc;
            desc.setAttribute('data-i18n', 'js.noDesc');
          }

          var link = document.createElement('a');
          link.href = repo.html_url;
          link.target = '_blank';
          link.rel = 'noopener noreferrer';
          link.className = 'case-link text-[11px] font-semibold uppercase tracking-[0.2em] text-[#1d1d1f] inline-flex items-center gap-2';
          link.innerHTML = '<span data-i18n="js.viewGithub">' + EN.viewGithub + '</span> <svg class="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M7 17L17 7M17 7H7M17 7v10"/></svg>';

          card.appendChild(title);
          card.appendChild(desc);
          card.appendChild(link);
          projectsGrid.appendChild(card);
        });

        // Load More button
        if (loadMoreWrap) {
          loadMoreWrap.innerHTML = '';
          if (repos.length >= PER_PAGE) {
            var btn = document.createElement('button');
            btn.className = 'case-link text-[11px] font-semibold uppercase tracking-[0.2em] text-[#1d1d1f] border border-gray-300 px-8 py-4 inline-flex items-center gap-2 hover:border-[#1d1d1f] transition-colors';
            btn.innerHTML = '<span data-i18n="js.loadMore">' + EN.loadMore + '</span> <svg class="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 9l-7 7-7-7"/></svg>';
            btn.addEventListener('click', function () {
              projectsPage++;
              btn.textContent = t('loading');
              btn.disabled = true;
              loadProjects(true);
            });
            loadMoreWrap.appendChild(btn);
          }
        }

        // Sync any newly added cards/button with the current language.
        renderLang();
      })
      .catch(function (err) {
        console.error('Error loading projects:', err);
        if (loadingProjects) {
          loadingProjects.style.display = '';
          loadingProjects.removeAttribute('data-en');
          loadingProjects.setAttribute('data-i18n', 'js.projectsError');
          loadingProjects.textContent = EN.projectsError;
          renderLang();
        }
      });
  }

  loadProjects(false);

  // ---- Contact Form AJAX ----
  var contactForm = document.getElementById('contact-form');
  if (contactForm) {
    contactForm.addEventListener('submit', function (e) {
      e.preventDefault();
      var btn = contactForm.querySelector('button[type="submit"]');
      var originalHTML = btn.innerHTML;
      btn.textContent = t('sending');
      btn.disabled = true;

      fetch(contactForm.action, {
        method: 'POST',
        body: new FormData(contactForm),
        headers: { 'Accept': 'application/json' }
      })
        .then(function (res) {
          if (res.ok) {
            contactForm.reset();
            btn.textContent = t('sent');
            setTimeout(function () {
              btn.innerHTML = originalHTML;
              btn.disabled = false;
            }, 3000);
          } else {
            throw new Error('Form submission failed');
          }
        })
        .catch(function () {
          btn.textContent = t('formError');
          btn.disabled = false;
          setTimeout(function () {
            btn.innerHTML = originalHTML;
          }, 3000);
        });
    });
  }

  // ---- Video Play Buttons ----
  document.querySelectorAll('.video-play-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
      var container = btn.closest('.group') || btn.parentElement;
      var video = container ? container.querySelector('video') : null;
      if (video) {
        if (video.paused) {
          video.play();
          btn.style.opacity = '0';
        } else {
          video.pause();
          btn.style.opacity = '';
        }
      }
    });
  });

  // ---- Smooth Scroll for Hash Links ----
  document.querySelectorAll('a[href^="#"]').forEach(function (anchor) {
    anchor.addEventListener('click', function (e) {
      var hash = this.getAttribute('href');
      if (!hash || hash === '#') return;
      var target = document.querySelector(hash);
      if (target) {
        e.preventDefault();
        var headerHeight = header ? header.getBoundingClientRect().height : 64;
        var top = target.getBoundingClientRect().top + window.scrollY - headerHeight - 16;
        window.scrollTo({ top: top, behavior: 'smooth' });
        // Close mobile menu if open
        if (mobileMenu && !mobileMenu.classList.contains('hidden')) {
          mobileMenu.classList.add('hidden');
          if (iconOpen) iconOpen.classList.remove('hidden');
          if (iconClose) iconClose.classList.add('hidden');
        }
      }
    });
  });

});
